#OPERADORES ARITMÉTICOS

a = 10;
b = 5;

print(a // b);
print(a % b);
print(a ** b);

#OPERADORES DE COMPARAÇÃO

print(10 > 5);
print(10 < 5);
print(10 == 10);
print(10 != 5);
print(10 >= 8);
print(10 <= 7);

#CONDICIONAL IF/ELSE

age = 20;

if age >= 18:
    print("of legal age");
else:
    print("minor");


#CONDICIONAL ELIF

grade = 8

if grade >= 9:
    print("Excellent");
elif grade >= 7:
    print("Good");
elif grade >= 5:
    print("Recuperation");
else:
    ("Failed")
